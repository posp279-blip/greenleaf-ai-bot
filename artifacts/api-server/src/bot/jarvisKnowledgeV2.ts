const STOP_WORDS = new Set([
  "и", "в", "во", "на", "не", "что", "это", "как", "я", "мы", "ты", "он", "она", "они",
  "мне", "ему", "ей", "у", "к", "по", "с", "со", "а", "но", "или", "же", "бы", "для", "из",
  "про", "до", "от", "за", "то", "так", "вот", "когда", "если", "уже", "ещё", "еще", "хочу",
]);

function normalize(value: string): string {
  return value.toLowerCase().replace(/ё/g, "е");
}

function tokenize(value: string): string[] {
  return normalize(value)
    .replace(/[^a-zа-я0-9]+/giu, " ")
    .split(/\s+/)
    .map((token) => token.trim())
    .filter((token) => token.length > 2 && !STOP_WORDS.has(token));
}

function phraseBoost(query: string, chunk: JarvisKnowledgeChunk): number {
  const q = normalize(query);
  let score = 0;

  const rules: Array<[RegExp, string[], number]> = [
    [/холодн|незнаком|наблюдател/, ["cold_context_joining", "online_three_criteria", "hook_context_question"], 35],
    [/подписан|подписчик|молчит/, ["cold_subscriber_message_logic", "hook_context_question"], 32],
    [/сторис|пост|публикац|реакц|лайк/, ["cold_story_viewer_logic", "hook_context_question"], 30],
    [/перв.*сообщ|перв.*касани|как начать/, ["hook_context_question", "online_three_criteria", "no_pressure_core"], 28],
    [/давно.*не общ|бывш.*коллег|знаком/, ["warm_reconnect_first", "no_pressure_core"], 28],
    [/дорог|цена|сумм.*вход|стартов.*пакет/, ["objection_price", "objection_join_clarify"], 30],
    [/пирамид/, ["objection_pyramid", "objection_join_clarify"], 32],
    [/дорог.*пирамид|пирамид.*дорог/, ["objection_two_at_once"], 45],
    [/встреч|созвон|зум|zoom/, ["meeting_first_contact_goal", "meeting_if_asks_details"], 28],
    [/переписк|где.*ошиб|разбери/, ["conversation_analysis", "no_pressure_core"], 28],
    [/нович|сдул|боится.*пис|первая недел/, ["newcomer_small_wins", "newcomer_support"], 30],
    [/спящ|реактив|пропал.*партн/, ["reactivate_partner"], 35],
  ];

  for (const [pattern, keys, boost] of rules) {
    if (pattern.test(q) && keys.includes(chunk.key)) score += boost;
  }
  return score;
}

export function retrieveJarvisKnowledge(query: string, limit = 8): JarvisKnowledgeChunk[] {
  const queryTokens = new Set(tokenize(query));
  const scored = JARVIS_KNOWLEDGE_V2.map((chunk) => {
    const titleTokens = tokenize(chunk.title);
    const tagTokens = tokenize(chunk.tags.join(" "));
    const contentTokens = new Set(tokenize(chunk.content));
    let score = chunk.priority + phraseBoost(query, chunk);

    for (const token of queryTokens) {
      if (titleTokens.includes(token)) score += 10;
      if (tagTokens.includes(token)) score += 8;
      if (contentTokens.has(token)) score += 2;
    }

    return { chunk, score };
  });

  const selected = scored
    .filter((item) => item.score > 7)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.chunk);

  if (!selected.some((chunk) => chunk.key === "jarvis_core")) {
    const core = JARVIS_KNOWLEDGE_V2.find((chunk) => chunk.key === "jarvis_core");
    if (core && selected.length < limit) selected.push(core);
  }

  return selected;
}
