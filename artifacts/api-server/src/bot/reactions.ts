export function getLaundryReaction(intent: string, brandName?: string): string {
  const brand = brandName || "это средство";
  switch (intent) {
    case "mass_market_brand":
      return `Понял, ${brand}. Это привычное средство — часто берут по рекламе, акции или просто по привычке.\n\nНо средство для стирки — это не просто «постирал и смылось». Одежда, полотенца и постель потом каждый день контактируют с кожей.\n\nДавай спокойно посмотрим, какие компоненты там обычно бывают.`;
    case "eco_brand":
      return `Хороший выбор — видно, что ты уже обращаешь внимание на то, чем стираешь.\n\nТогда у нас вопрос будет не столько про качество, сколько про выгоду: сколько это стоит за год, насколько экономно расходуется и есть ли альтернатива такого же уровня, но дешевле.`;
    case "unknown":
      return `Нормально, большинство не помнит название. Тогда возьмём средний пример популярного средства из магазина — логика будет понятна в любом случае.`;
    case "not_used":
      return `Окей. Тогда посмотрим на эту категорию как на семейную — если рядом есть кто-то, кто стирает, цифры всё равно будут полезны.`;
    default:
      return `Понял. Давай разберём, на что стоит обращать внимание в средствах для стирки.`;
  }
}

