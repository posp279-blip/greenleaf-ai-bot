// Fallback template reactions when AI is unavailable
// These are used as a backup when the Proxy API is down.
// Style: warm, friendly, conversational — like explaining to a friend.

export function getLaundryReaction(intent: string, brandName?: string): string {
  const brand = brandName || "это средство";
  switch (intent) {
    case "mass_market_brand":
      return `Понял, ${brand}. Его многие берут просто на автомате: бренд знакомый, запах привычный, часто бывает по акции.

Я не буду пугать тебя химией, тут не про страшилки.

Просто есть момент: после стирки одежда, полотенца и постель каждый день касаются кожи. Поэтому важно смотреть не только на запах и цену пачки, а ещё на состав, выполаскивание и расход.

Хочешь, я коротко покажу, почему такие привычные средства не всегда самый выгодный и спокойный вариант?`;

    case "eco_brand":
      return `Круто, значит ты уже смотришь, чем стираешь. Это редко.

Тогда вопрос будет не "хорошо ли оно", а "сколько оно стоит за год" и "есть ли альтернатива такого же уровня, но дешевле".

Давай просто сравним цифры. Готов?`;
    case "unknown":
      return `Нормально, многие не помнят название. Берут что под рукой или что по акции.

Давай возьмём средний пример популярного средства из магазина — логика будет понятна в любом случае.

Посмотрим вместе?`;
    case "not_used":
      return `Окей, ты сам не стираешь. Но эта категория есть почти в каждом доме — если рядом есть кто-то, кто стирает, цифры всё равно будут полезны.

Посмотрим вместе?`;
    default:
      return `Понял. Давай просто посмотрим, на что стоит обращать внимание в средствах для стирки и почему обычный магазин стоит пересмотреть. Посмотрим?`;
  }
}

