const STOP_WORDS = new Set([
  "и", "в", "во", "на", "не", "что", "это", "как", "я", "мы", "ты", "он", "она", "они",
  "мне", "ему", "ей", "у", "к", "по", "с", "со", "а", "но", "или", "же", "бы", "для", "из",
  "про", "до", "от", "за", "то", "так", "вот", "когда", "если", "уже", "ещё", "еще",
]);

function tokenize(value: string): string[] {
  return value
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/giu, " ")
    .split(/\s+/)
    .map((token) => token.trim())
    .filter((token) => token.length > 2 && !STOP_WORDS.has(token));
}

export function retrieveJarvisKnowledge(query: string, limit = 5): JarvisKnowledgeChunk[] {
  const queryTokens = new Set(tokenize(query));
  if (queryTokens.size === 0) {
    return JARVIS_KNOWLEDGE.filter((chunk) => chunk.key === "jarvis_core");
  }

  const scored = JARVIS_KNOWLEDGE.map((chunk) => {
    const titleTokens = tokenize(chunk.title);
    const tagTokens = tokenize(chunk.tags.join(" "));
    const contentTokens = tokenize(chunk.content);

    let score = 0;
    for (const token of queryTokens) {
      if (titleTokens.includes(token)) score += 8;
      if (tagTokens.includes(token)) score += 6;
      if (contentTokens.includes(token)) score += 2;
    }

    // Small prior for the core guidance so it is available when scores are sparse.
    if (chunk.key === "jarvis_core") score += 1;
    return { chunk, score };
  });

  const positive = scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.chunk);

  if (!positive.some((chunk) => chunk.key === "jarvis_core")) {
    const core = JARVIS_KNOWLEDGE.find((chunk) => chunk.key === "jarvis_core");
    if (core && positive.length < limit) positive.push(core);
  }

  return positive.length > 0 ? positive : JARVIS_KNOWLEDGE.slice(-1);
}
